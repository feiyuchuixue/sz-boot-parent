package com.sz.resource.enums;

/**
 * 资源命名规则
 *
 * <p>
 * 控制上传文件名的生成方式。各候选值的命名效果和冲突处理规则见对应枚举常量说明。
 */
public enum NamingRuleEnum {

    /**
     * 使用业务 Key 命名。 文件名为调用方提供的 namingKey 加原文件最后一段扩展名的小写形式，无扩展名时使用 bin，例如
     * github.svg。namingKey 必须非空白，其中 ASCII 字母、数字、下划线、连字符以外的字符会替换为下划线；同一路径同 key
     * 重传可覆盖旧文件。
     */
    BIZ_KEY,

    /**
     * 使用随机 UUID 命名。 文件名为无连字符 UUID 加原文件最后一段扩展名的小写形式，无扩展名时使用 bin，例如
     * 550e8400e29b41d4a716446655440000.svg；每次上传生成新文件。
     */
    UUID,

    /**
     * 使用清洗后的原始文件名。 保留 ASCII 字母、数字、下划线、连字符、点及 U+4E00-U+9FA5 范围汉字，其他字符替换为下划线。目标
     * objectKey 已存在时 仅检查一次并在扩展名前追加下划线和当前毫秒时间戳；该处理降低同名冲突，不保证并发上传绝对不覆盖。
     */
    ORIGINAL,

    /**
     * 使用毫秒精度时间戳命名。 文件名为 yyyyMMddHHmmssSSS 加原文件最后一段扩展名的小写形式，无扩展名时使用 bin，例如
     * 20260416143025123.pdf； 高并发下仍可能冲突，可结合路径策略分散。
     */
    TIMESTAMP
}
